--  La bonne source existait : le MINISTÈRE lui-même. La DPCE a
--  publié, pour le recensement 2024-2025, DIX REGISTRES
--  DÉPARTEMENTAUX qui listent les écoles une par une, avec leur
--  code officiel, leur adresse et leur niveau d'enseignement.
--
--  Ce sont des PDF de 408 pages pour l'Ouest. On les a lus.
--
--  ── Ce que le code d'établissement contient ───────────────────
--
--   0 5 1 3 | 0 2 | 2 | 0 8 2 4 3
--   └──┬──┘   └┬┘   │   └───┬───┘
--      │       │    │       └── numéro d'ordre
--      │       │    └────────── secteur : 1 public, 2 non public
--      │       └─────────────── section communale
--      └─────────────────────── P-CODE de la commune (HT0513)
--
--  Les quatre premiers chiffres sont EXACTEMENT le P-code officiel.
--  C'est donc le code qui donne la commune et le secteur, pas les
--  en-têtes de page — qui se coupent en deux et se prêtent mal au
--  découpage. Le rattachement est exact, pas approché.
--
--  ── Ce que la lecture donne ───────────────────────────────────
--
--  17 902 écoles distinctes, dans les 146 communes, pour les 10
--  départements. Le recensement officiel en annonce 18 241 : on en
--  a donc 98 %.
--
--  Deux contrôles qui rassurent :
--
--  · la répartition trouvée — 82 % non public, 18 % public — est
--    exactement celle que le ministère publie ;
--  · sur 146 P-codes, 140 correspondent au référentiel des
--    communes au caractère près.
--
--  ── UNION, et non remplacement ────────────────────────────────
--
--  6 898 écoles du référentiel actuel ne figurent PAS dans le
--  recensement, et ce sont de vraies écoles (« École Mixte Frère
--  Nau », « École Mixte Notre Dame du Mont Carmel »…). On garde
--  donc tout : ce qui compte est qu'un élève trouve la sienne.
--
--  Le prix est quelques doublons approchants — environ 700 sur
--  25 000, soit 2,6 %. Les doublons EXACTS, eux, sont écartés par
--  l'index unique (commune, nom normalisé), et le code officiel est
--  unique de son côté.
